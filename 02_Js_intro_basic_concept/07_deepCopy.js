
let num1 = 100;
// 👉 We create a variable called num1 and store the value 100 in it.

let num2 = num1;

// We copy the value of num1 into num2.

console.log("num1 value", num1);

// This prints the current value of num1.

console.log("num2 value", num2);

// This prints the current value of num2.

num2 = 500;
// Now we change the value of num2 from 100 to 500.
console.log("num1 value", num1);
// This prints num1.
console.log("num2 value", num2);
// This prints num2.